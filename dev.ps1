<#
Dev environment helper. Run from the project folder:  .\dev.ps1 <command>

  setup    FIRST TIME: start local Supabase, create .env.docker, build API, migrate, seed
  up       start local Supabase + API          -> http://localhost:8000/docs
  down     stop everything (local data is kept)
  logs     follow API logs (fake OTP codes appear here). Ctrl+C stops following only
  test     run pytest inside the API container
  migrate  apply db/migrations to the LOCAL database
  info     show LOCAL migration status
  seed     load db/seed/*.sql (fictional data) into the LOCAL database
  status   show local URLs, keys and running containers
  reset    WIPE the LOCAL database, then migrate + seed

Everything here touches ONLY your local database. The shared cloud database
is migrated separately with db\flyway.ps1 (after the PR is merged into dev).
#>
param([Parameter(Position = 0)][string]$Command = "help")
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

function Assert-Ok([string]$what) {
  if ($LASTEXITCODE -ne 0) { throw "$what failed (exit code $LASTEXITCODE). Read the output above." }
}

function Assert-Tools {
  if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { throw "Docker not found. Install Docker Desktop and start it." }
  $ErrorActionPreference = "Continue"   # PS 5.1: stderr warnings must not abort
  docker info *> $null
  $dockerOk = ($LASTEXITCODE -eq 0)
  $ErrorActionPreference = "Stop"
  if (-not $dockerOk) { throw "Docker is installed but not running. Start Docker Desktop and wait for 'Engine running'." }
  if (-not (Get-Command node -ErrorAction SilentlyContinue)) { throw "Node.js not found. Install Node.js 20 LTS or newer (needed for the Supabase CLI)." }
  $major = [int]((node -v).TrimStart("v").Split(".")[0])
  if ($major -lt 20) { throw "Node.js $(node -v) is too old. The Supabase CLI needs Node.js 20 or newer." }
  if (-not (Test-Path .\supabase\config.toml)) {
    throw "supabase\config.toml is missing. It is committed in the repo: pull the latest dev branch."
  }
  if (-not (Test-Path .\.env)) {
    throw ".env is missing. Copy .env.example to .env and fill in the MEDISINA_* values (see docs\DEV_ENVIRONMENT.md)."
  }
}

function Start-LocalSupabase {
  Write-Host "Starting local Supabase (first time downloads ~1 GB of images)..." -ForegroundColor Cyan
  npx --yes supabase start
  Assert-Ok "supabase start"
}

function Write-EnvDocker {
  $vals = @{}
  $ErrorActionPreference = "Continue"   # npx writes notices to stderr; don't treat them as errors
  $statusLines = npx --yes supabase status -o env 2>$null
  $ErrorActionPreference = "Stop"
  foreach ($line in $statusLines) {
    if ($line -match '^([A-Z_]+)="?(.*?)"?$') { $vals[$Matches[1]] = $Matches[2] }
  }
  $key = $vals["SECRET_KEY"]
  if (-not $key) { $key = $vals["SERVICE_ROLE_KEY"] }
  if (-not $key) { throw "Could not read the local secret key from 'npx supabase status -o env'. Paste that command's output to Claude." }

  # keep an existing token secret so issued tokens stay valid across setups
  $secret = $null
  if (Test-Path .\.env.docker) {
    $m = Select-String -Path .\.env.docker -Pattern '^OTP_TOKEN_SECRET=(.+)$'
    if ($m) { $secret = $m.Matches[0].Groups[1].Value }
  }
  if (-not $secret) {
    $bytes = New-Object byte[] 48
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $secret = [Convert]::ToBase64String($bytes)
  }
  $content = @(
    "# Generated by .\dev.ps1 - overrides .env inside Docker. LOCAL Supabase only. Not committed.",
    "SUPABASE_URL=http://host.docker.internal:54321",
    "SUPABASE_SECRET_KEY=$key",
    "APP_ENV=local",
    "OTP_PROVIDER=fake",
    "OTP_TOKEN_SECRET=$secret"
  ) -join "`n"
  [IO.File]::WriteAllText((Join-Path $PWD.Path ".env.docker"), $content + "`n")
  Write-Host "wrote .env.docker"
}

function Invoke-Migrate { docker compose run --rm flyway migrate; Assert-Ok "flyway migrate" }
function Invoke-Seed    { docker compose run --rm seed;           Assert-Ok "seed" }

function Show-Urls {
  Write-Host ""
  Write-Host "API docs     http://localhost:8000/docs" -ForegroundColor Green
  Write-Host "API health   http://localhost:8000/health/db" -ForegroundColor Green
  Write-Host "DB Studio    http://localhost:54323   (browse local tables)" -ForegroundColor Green
  Write-Host "Fake OTP codes:  .\dev.ps1 logs" -ForegroundColor Green
}

switch ($Command) {
  "setup" {
    Assert-Tools
    Start-LocalSupabase
    Write-EnvDocker
    docker compose build api; Assert-Ok "docker compose build"
    Invoke-Migrate
    Invoke-Seed
    docker compose up -d api; Assert-Ok "docker compose up"
    Show-Urls
  }
  "up" {
    Assert-Tools
    Start-LocalSupabase
    if (-not (Test-Path .\.env.docker)) { Write-EnvDocker }
    docker compose up -d --build api; Assert-Ok "docker compose up"
    Show-Urls
  }
  "down" {
    docker compose down
    npx --yes supabase stop
  }
  "logs"    { docker compose logs -f api }
  "test"    { docker compose run --rm api pytest -q; Assert-Ok "pytest" }
  "migrate" { Invoke-Migrate }
  "info"    { docker compose run --rm flyway info; Assert-Ok "flyway info" }
  "seed"    { Invoke-Seed }
  "status"  { npx --yes supabase status; docker compose ps }
  "reset" {
    Write-Host "This WIPES the LOCAL database (cloud is not touched)." -ForegroundColor Yellow
    if ((Read-Host "Type RESET to continue") -ne "RESET") { Write-Host "Cancelled."; return }
    npx --yes supabase db reset; Assert-Ok "supabase db reset"
    Invoke-Migrate
    Invoke-Seed
  }
  default { Get-Content $PSCommandPath -TotalCount 19 | Select-Object -Skip 1 | ForEach-Object { Write-Host $_ } }
}
